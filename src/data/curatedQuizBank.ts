// Generates 10 practice questions for chapter and milestone
export function getCuratedQuestionsForChapter(
  subject: SubjectType,
  chapterName: string,
  milestoneKey: MilestoneKey
): QuizQuestion[] {
  const bank = CURATED_QUIZ_QUESTIONS[subject] || CURATED_QUIZ_QUESTIONS.Math;
  
  // Clone and personalize milestone focus
  const milestoneLabelMap: Record<MilestoneKey, string> = {
    theory: 'Theory Concept Retention',
    conclusion1Page: '1-Page Summary & Key Traps',
    mathongo: 'MathonGo Concept Builder Drill',
    moduleEx2: 'Module Ex-2 Standard Drill',
    eklavya: 'Eklavya Advanced Multi-Concept',
    prevPartTest: 'Part Test Previous Paper Drill',
  };

  const focus = milestoneLabelMap[milestoneKey] || 'Practice Drill';

  // Shuffle or reorder
  const shuffled = [...bank].sort(() => Math.random() - 0.5);
  
  // Take 10 questions (or repeat/wrap if bank is short)
  const result: QuizQuestion[] = [];
  for (let i = 0; i < 10; i++) {
    const base = shuffled[i % shuffled.length];
    result.push({
      ...base,
      id: i + 1,
      milestoneFocus: `${chapterName} • ${focus}`,
    });
  }

  return result;
}
